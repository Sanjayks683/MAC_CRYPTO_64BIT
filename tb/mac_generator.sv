        txn.mac_en    = 1'b1;
        txn.clear_acc = 1'b1;
        txn.stall     = 1'b0;
        txn.flush     = 1'b0;
        txn.modulus   = {128{1'b1}};
        drv_mbx.put(txn);
        count++;
        while (count < num_txns) begin
            txn = new();
            assert(txn.randomize()) else $error("GEN: Randomization failed");
            drv_mbx.put(txn);
            count++;
        end
        $display("[%0t] GEN: Done — %0d transactions generated", $time, count);
        -> done;
    endtask
endclass
